"use client";

import { Switch } from "@/components/ui/switch";
import { Shield, Loader2 } from "lucide-react";
import { useState } from "react";

export function Teammate2FATab({ isEnabled = false }: { isEnabled?: boolean }) {
  const [enabled, setEnabled] = useState(isEnabled);
  const [isUpdating, setIsUpdating] = useState(false);

  const handleToggle = async (checked: boolean) => {
    setIsUpdating(true);
    setEnabled(checked);
    await new Promise(r => setTimeout(r, 800));
    setIsUpdating(false);
  };

  return (
    <div className="flex flex-col h-full animate-in fade-in duration-500 max-w-3xl">
      <div className="rounded-xl border border-border bg-background p-8">
        <div className="flex items-start justify-between">
          <div className="flex gap-4">
            <div className="size-10 rounded-lg bg-[#6b5eed]/10 flex items-center justify-center shrink-0">
              <Shield className="size-5 text-[#6b5eed]" />
            </div>
            <div>
              <h3 className="text-lg font-bold text-foreground mb-2">Two-factor authentication</h3>
              <p className="text-sm text-muted-foreground leading-relaxed max-w-xl">
                Add an extra layer of security to your account. Once enabled, you'll be required to enter a unique code generated by an authentication app on your phone whenever you sign in.
              </p>
            </div>
          </div>
          
          <div className="flex items-center gap-3">
            {isUpdating && <Loader2 className="size-4 text-muted-foreground animate-spin" />}
            <Switch 
              checked={enabled}
              onCheckedChange={handleToggle}
              className="data-[state=checked]:bg-[#6b5eed]"
            />
          </div>
        </div>

        {enabled && (
          <div className="mt-8 p-4 rounded-lg bg-green-500/10 border border-green-500/20 text-green-400 text-sm flex items-center gap-2 animate-in fade-in slide-in-from-top-2">
            <Shield className="size-4" />
            Two-factor authentication is currently active.
          </div>
        )}
      </div>
    </div>
  );
}
